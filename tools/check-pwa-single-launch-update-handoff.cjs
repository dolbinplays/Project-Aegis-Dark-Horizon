#!/usr/bin/env node
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const runtime=fs.readFileSync(path.join(root,'src','browser-runtime.html'),'utf8');
const host=fs.readFileSync(path.join(root,'index.html'),'utf8');
const worker=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'src','manifest.json'),'utf8'));
const tests=[];const add=(name,pass)=>tests.push({name,pass:Boolean(pass)});
add('current build remains synchronized',runtime.includes(`const CURRENT_GAME_BUILD="${manifest.currentBuild}"`)&&host.includes(`const BUILD='${manifest.currentBuild}'`));
add('1708 PWA lineage flag remains present',runtime.includes('const PWA_SINGLE_LAUNCH_UPDATE_HANDOFF_PATCH=true;'));
add('1708 patch history remains frozen',runtime.includes('build:"v0.26.09.11.1708_PWA_SINGLE_LAUNCH_UPDATE_HANDOFF_PATCH",date:"September 11, 2026",title:"Installed PWA Single-Launch Update Handoff"'));
add('1800 supersession flag is present',runtime.includes('const PWA_ANDROID_COLD_START_RELEASE_BEACON_HOTFIX=true;'));
add('blocking preboot update gate intentionally removed',!host.includes('prepareInstalledPwaStartup')&&!host.includes('PWA_UPDATE_ACTIVATION_TIMEOUT_MS'));
add('controller-change forced reload intentionally removed',!host.includes('window.location.reload()')&&!host.includes('addEventListener("controllerchange"'));
add('runtime boots immediately',host.includes('bootRuntime();')&&host.includes('setTimeout(refreshAegisServiceWorkerInBackground,0)'));
add('service worker updates continue in background',host.includes('registration.update?.().catch'));
add('service worker registration still bypasses script cache',host.includes('updateViaCache:"none"'));
add('release-beacon navigation strategy is active',host.includes('release-beacon-navigation-v2')&&worker.includes('aegis_probe'));
add('stable launch cache bridges worker generations',worker.includes('aegis-launch-shell-v2'));
add('worker install no longer precaches index.html',worker.includes('AEGIS_SMALL_SHELL')&&!((worker.match(/const AEGIS_SMALL_SHELL = \[([\s\S]*?)\];/)||[])[1]||'').includes('index.html'));
add('worker still supports skipWaiting',worker.includes('AEGIS_SKIP_WAITING')&&worker.includes('self.skipWaiting'));
add('worker still claims clients',worker.includes('self.clients.claim()'));
add('save format remains 4',runtime.includes('const CURRENT_SAVE_FORMAT_VERSION=4;'));
const passed=tests.filter(t=>t.pass).length;
for(const t of tests)console.log(`${t.pass?'PASS':'FAIL'} - ${t.name}`);
console.log(`\nPassed: ${passed}/${tests.length}`);console.log(`Failed: ${tests.length-passed}`);
if(passed!==tests.length)process.exit(1);
