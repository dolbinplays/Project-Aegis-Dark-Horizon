#!/usr/bin/env node
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const build='v0.26.09.11.1448_PROCEDURAL_BUILDING_FACADE_CONNECTOR_INFILL_HOTFIX';
const runtime=fs.readFileSync(path.join(root,'src','browser-runtime.html'),'utf8');
const index=fs.readFileSync(path.join(root,'index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'service-worker.js'),'utf8');
const notes=fs.readFileSync(path.join(root,'README_PATCH_NOTES.txt'),'utf8');
const roadmap=fs.readFileSync(path.join(root,'Project_Aegis_Alien_Response_Command_Updated_Roadmap_and_Game_Bible.md'),'utf8');
const handoff=fs.readFileSync(path.join(root,'CODEX_HANDOFF.md'),'utf8');
const field=fs.readFileSync(path.join(root,'PROCEDURAL_BUILDING_FACADE_CONNECTOR_INFILL_FIELD_ACCEPTANCE.txt'),'utf8');
const meta=JSON.parse(fs.readFileSync(path.join(root,'release-metadata.json'),'utf8'));
const merge=JSON.parse(fs.readFileSync(path.join(root,'src','manifest.1448.merge.json'),'utf8'));
const checks=[];
const add=(name,pass)=>checks.push({name,pass:Boolean(pass)});
add('Runtime build is Browser 1448',runtime.includes(`const CURRENT_GAME_BUILD="${build}"`));
add('Save format remains 4',runtime.includes('const CURRENT_SAVE_FORMAT_VERSION=4'));
add('Facade connector patch flag is enabled',runtime.includes('const PROCEDURAL_BUILDING_FACADE_CONNECTOR_INFILL_HOTFIX = true'));
add('Facade connector helper is present',runtime.includes('function tacticalThreeFacadeConnectorInfillScale(distance = 0)'));
add('Helper measures only uncovered gap',runtime.includes('Number(distance || 0) - 1.06'));
add('Window connector still has sill',runtime.includes('windowWallConnector="sill"'));
add('Window connector still has lintel',runtime.includes('windowWallConnector="lintel"'));
add('Window connector adds full-height facade infill',runtime.includes('infill.scale.set(infillScale,3.15,0.78)')&&runtime.includes('windowWallConnector="facade-infill"'));
add('Infill is centered between neighboring cells',runtime.includes('infill.position.set(dx/2,0.82,dz/2)'));
add('Window aperture meshes remain present',runtime.includes('windowAperture="lower"')&&runtime.includes('windowAperture="lintel"')&&runtime.includes('windowAperture="jamb"'));
add('Transparent window pane remains present',runtime.includes('window-pane-transparent')&&runtime.includes('windowTransparent=true'));
add('Generated doors remain excluded from structural covers',runtime.includes('if(!cell?.perimeter||cell.door)continue'));
add('Structural connector excludes breaches/dead structural parts',runtime.includes('function tacticalConnectedStructuralWalls')&&runtime.includes('tacticalStructuralConnectorOwnedBy'));
add('Browser 1410 discovered shell patch remains enabled',runtime.includes('const PROCEDURAL_BUILDING_DISCOVERED_WALL_SHELL_CLOSURE_PATCH = true'));
add('Discovered shell presentation helper remains present',runtime.includes('function tacticalThreeBuildingPresentationCovers'));
add('Patch-specific live contract is registered',runtime.includes('tacticalProceduralBuildingFacadeConnectorInfillTest'));
add('Current patch history entry is present',runtime.includes('title:"Procedural Building Facade Connector Infill Hotfix"'));
add('Exactly one mutable current history entry', (runtime.match(/^PATCH_NOTES_HISTORY\.unshift\(\{build:CURRENT_GAME_BUILD/gm)||[]).length===1);
add('Host build is synchronized',index.includes(build));
add('Service-worker caches are synchronized',sw.includes(`aegis-${build}`)&&sw.includes(`aegis-runtime-${build}`));
add('Release metadata is synchronized',meta.build===build&&meta.save_format===4&&meta.package_filename===`Project_Aegis_${build}.zip`);
add('Patch notes are synchronized',notes.startsWith('PROJECT AEGIS / ALIEN RESPONSE COMMAND')&&notes.includes(`BUILD: ${build}`));
add('Roadmap current build is synchronized',roadmap.includes(`Current browser build: \`${build}\``)&&roadmap.includes('Browser 1448'));
add('PWA single-launch roadmap item preserved',roadmap.includes('Installed PWA Single-Launch Update Handoff'));
add('Mobile HUD collapse roadmap item preserved',roadmap.includes('Mobile Tactical Status HUD Collapse / Expand'));
add('Codex handoff is synchronized',handoff.startsWith(`# CODEX HANDOFF — ${build}`));
add('Field acceptance is synchronized',field.includes(`Build: ${build}`));
add('Manifest merge is synchronized',merge.currentBuild===build&&merge.lastInspectedBuild===build&&merge.gameplayParity?.browserBuild===build);
add('Non-destructive updater is present',fs.existsSync(path.join(root,'tools','apply-1448-source-manifest.cjs'))&&fs.existsSync(path.join(root,'APPLY_1448_SOURCE_MANIFEST.bat')));
add('Browser 1254 horizon patch remains in history',runtime.includes('Tactical Horizon Fog-Integrated Solid Depth Fade Hotfix'));
let passed=0;
for(const c of checks){console.log(`${c.pass?'PASS':'FAIL'} - ${c.name}`);if(c.pass)passed++;}
console.log(`\nPassed: ${passed}/${checks.length}`);
console.log(`Failed: ${checks.length-passed}`);
process.exit(passed===checks.length?0:1);
